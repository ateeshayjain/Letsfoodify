#!/usr/bin/env python3
"""Render preview/devices.html — the storefront at desktop and phone width.

NOT A MOCKUP. Both frames load the SAME generated storefront document; the
phone frame is simply 390 CSS pixels wide, so the theme's own media queries
(900/782/560px) produce the mobile layout for real. If mobile looks wrong
here, mobile IS wrong — which is the point of looking.

The storefront HTML is embedded once and fed to both iframes via srcdoc, so
this file cannot drift from the preview it wraps. Regenerate after any
render-preview.py run:

    python3 tools/render-preview.py && python3 tools/render-device-view.py
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC  = os.path.join(HERE, "..", "preview", "storefront.html")
OUT  = os.path.join(HERE, "..", "preview", "devices.html")

store = open(SRC, encoding="utf-8").read()
# Inside a <script> block, a literal "</script>" in the payload ends the block
# early and truncates everything after it — the same stop-parsing-at-one-byte
# failure the feed's ampersand had. JSON-encode, then break the sequence.
payload = json.dumps(store).replace("</", "<\\/")

doc = r"""<title>Foodify Device Preview</title>
<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Fraunces:opsz,wght@9..144,400..700&family=Instrument+Sans:wght@400..700&display=swap">
<style>
:root{--paper:#FDFBF7;--surface:#FFFFFF;--char:#2B2A27;--mute:#7A736A;--line:#E6DCCB;
--kraft-pale:#F4EBDF;--kraft-deep:#8A5A28;--display:"Fraunces",Georgia,serif;--ui:"Instrument Sans",system-ui,sans-serif}
body{background:var(--kraft-pale);color:var(--char);font:15px/1.55 var(--ui);margin:0}
header{max-width:80rem;margin:0 auto;padding:2rem 1.5rem .5rem}
h1{font-family:var(--display);font-weight:600;font-size:1.7rem;margin:0;text-wrap:balance}
header p{color:var(--kraft-deep);margin:.4rem 0 0;font-size:.85rem;max-width:52rem}
.stage{display:flex;gap:2rem;align-items:flex-start;justify-content:center;flex-wrap:wrap;
  max-width:80rem;margin:0 auto;padding:1.5rem}
.device{display:flex;flex-direction:column;gap:.6rem;align-items:center}
.device h2{font:600 .72rem/1 var(--ui);letter-spacing:.08em;text-transform:uppercase;color:var(--kraft-deep);margin:0}
/* Desktop: a real 1280px viewport, scaled by JS to fit the column. */
.desk-shell{border-radius:14px;background:var(--char);padding:10px 10px 14px;box-shadow:0 18px 40px rgba(43,42,39,.18)}
.desk-clip{overflow:hidden;border-radius:6px;background:var(--paper)}
.desk-clip iframe{width:1280px;height:840px;border:0;transform-origin:0 0;display:block}
/* Phone: 390 CSS px — iPhone-class width. Generic bezel, no brand hardware. */
.phone-shell{border-radius:44px;background:var(--char);padding:12px;box-shadow:0 18px 40px rgba(43,42,39,.22);position:relative}
.phone-shell::before{content:"";position:absolute;top:22px;left:50%;transform:translateX(-50%);
  width:88px;height:22px;border-radius:12px;background:var(--char);z-index:2}
.phone-clip{overflow:hidden;border-radius:32px;background:var(--paper)}
.phone-clip iframe{width:390px;height:740px;border:0;display:block}
.note{max-width:80rem;margin:0 auto;padding:0 1.5rem 3rem;color:var(--mute);font-size:.8rem}
:focus-visible{outline:2px solid var(--kraft-deep);outline-offset:2px}
@media (prefers-reduced-motion: reduce){*{transition:none!important;animation:none!important}}
</style>
<header>
<h1>One theme, two widths</h1>
<p>Both frames load the same document, generated from the shipping theme &mdash; the phone frame is simply 390&nbsp;CSS pixels wide, so the theme&rsquo;s own breakpoints produce the mobile layout for real. Each device navigates independently: put desktop on Product and the phone on Checkout.</p>
</header>
<div class="stage">
  <div class="device"><h2>Desktop &middot; 1280px</h2>
    <div class="desk-shell"><div class="desk-clip" id="dclip"><iframe id="desk" title="Storefront at desktop width"></iframe></div></div>
  </div>
  <div class="device"><h2>Phone &middot; 390px</h2>
    <div class="phone-shell"><div class="phone-clip"><iframe id="phone" title="Storefront at phone width"></iframe></div></div>
  </div>
</div>
<p class="note">Scroll and click inside either frame. The nav collapses on the phone per the preview&rsquo;s breakpoint; on the live site WordPress&rsquo;s navigation block renders its hamburger overlay there &mdash; one of the things only staging can show. Generated by <code>tools/render-device-view.py</code>; never hand-edited.</p>
<script>
var STORE = __PAYLOAD__;
document.getElementById('desk').srcdoc = STORE;
document.getElementById('phone').srcdoc = STORE;
// Scale the 1280px desktop viewport to whatever column width is available.
function fit(){
  var clip = document.getElementById('dclip');
  var max = Math.min(document.querySelector('.stage').clientWidth - 480, 860);
  if (max < 320) { max = Math.min(document.querySelector('.stage').clientWidth - 40, 860); }
  var s = Math.max(0.25, Math.min(max / 1280, 0.75));
  var f = document.getElementById('desk');
  f.style.transform = 'scale(' + s + ')';
  clip.style.width  = (1280 * s) + 'px';
  clip.style.height = (840 * s) + 'px';
}
addEventListener('resize', fit); fit();
</script>
"""
doc = doc.replace("__PAYLOAD__", payload)
open(OUT, "w", encoding="utf-8").write(doc)
print(f"rendered {OUT}  ({len(doc):,} bytes)")
